#!/usr/bin/env python3
"""Builds shared/js/el-reference-data.js, the data of the teacher dashboard's 📖 Reference tab (Roger, 31 Oct 2026).

Sources:
  tools/reference/curriculum.json   English competences and criteria (Decret 175/2022, both bands), the course distribution of the
                                    integrated criteria, and the cross-curricular competences (XTEC) with their link to English.
  docs/2eso/programme.md, docs/4eso/programme.md   which criteria each LS assesses (the coverage tables).
  Gramatica_A1-B1_1r-4t_ESO.docx, Lexic_A1-B1_1r-4t_ESO.docx   the grammar and lexicon maps (Drive, Teacher Studio › 05).

Run again after an LS design or a change in the maps:
  python3 tools/reference/build-reference.py [grammar.docx] [lexicon.docx]
"""
import json, re, sys, pathlib
import docx  # python-docx

ROOT = pathlib.Path(__file__).resolve().parents[2]
MAPS = pathlib.Path("/mnt/project-files/maps-2026-10-31")
gram = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else MAPS / "Gramatica_A1-B1_1r-4t_ESO.docx"
lexi = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else MAPS / "Lexic_A1-B1_1r-4t_ESO.docx"

cur = json.load(open(ROOT / "tools/reference/curriculum.json"))

ENG = re.compile(r"^CE(\d+) ·")
TRANS = re.compile(r"^(CC\d|CPSAA \d|CD\d|CE\d emprenedora)$")


def cells(line):
    line = line.strip()
    if line.startswith("|"):
        return [c.strip() for c in line.strip("|").split("|")]
    return [c.strip() for c in re.split(r"\s{2,}", line)]


def programme(course):
    """{eng: {ce: [[crit...] x6]}, trans: {code: [[{n, o, ce}] x6]}} from the coverage tables (first occurrence only)."""
    eng, trans = {}, {}
    for line in open(ROOT / f"docs/{course}/programme.md", encoding="utf-8"):
        c = cells(line)
        if len(c) < 7:
            continue
        head = c[0].replace("*", "")
        m = ENG.match(head)
        if m and m.group(1) not in eng:
            eng[m.group(1)] = [re.findall(r"\d+\.\d+", x) for x in c[1:7]]
            continue
        if TRANS.match(head) and head not in trans:
            row = []
            for x in c[1:7]:
                mm = re.match(r"(\d+\.\d+)\s*\((O\d+),\s*(CE\d+)\)", x)
                row.append([{"n": mm.group(1), "o": mm.group(2), "ce": mm.group(3)}] if mm else [])
            trans[head] = row
    assert len(eng) == 10, (course, sorted(eng))
    assert len(trans) == 17, (course, sorted(trans))
    return {"eng": eng, "trans": trans}


ROUTES = {"I": "Base", "S": "Core", "D": "Plus", "Insecure": "Base", "Safe": "Core", "Daring": "Plus", "Beginners": "Starter"}


def routes(s):
    """Old route names → the names the site uses (Starter · Base · Core · Plus), only inside brackets, where they mean routes."""
    def fix(m):
        return "(" + re.sub(r"\b(Insecure|Safe|Daring|Beginners|I|S|D)\b", lambda r: ROUTES[r.group(1)], m.group(1)) + ")"
    return re.sub(r"\(([^()]*)\)", fix, s)


def table(path):
    d = docx.Document(str(path))
    rows = []
    for r in d.tables[0].rows[1:]:
        t = [c.text.strip() for c in r.cells]
        if len(set(t)) == 1:
            rows.append({"sec": t[0]})
            continue
        rows.append({"s": t[0], "cefr": t[1], "src": t[2], "c": [routes(x) for x in t[3:7]]})
    return rows


data = {
    "built": "2026-10-31",
    "source": cur["source"],
    "statements": cur["statements"],
    "criteria": cur["criteria"],
    "dist": cur["dist"],
    "transversal": cur["transversal"],
    "prog": {c: programme(c) for c in ("2eso", "4eso")},
    "grammar": table(gram),
    "lexicon": table(lexi),
}
out = ROOT / "shared/js/el-reference-data.js"
out.write_text("// Generated by tools/reference/build-reference.py: do not edit by hand (see that file for the sources).\n"
               "window.EL_REF=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
print(out, out.stat().st_size, "bytes;", len(data["grammar"]), "grammar rows,", len(data["lexicon"]), "lexicon rows")
