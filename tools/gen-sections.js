// Run: node tools/gen-sections.js .   Generates shared/js/el-sections.js: the section tabs of every activity page in EL_CATALOG
// (LS2 engine pages: window.LP.panels in the page's data/*.js; other pages: their <button class="tab" data-panel> list), so the
// dashboard can open or lock each section per group. Run it again when an activity page adds, removes or renames a section.
const fs=require("fs"),path=require("path"),vm=require("vm"),R=process.argv[2]||".";
global.window=global;require(path.resolve(R,"shared/js/el-catalog.js"));
const out={};
for(const a of EL_CATALOG){
  const file=path.join(R,a.path);if(!fs.existsSync(file))continue;
  const h=fs.readFileSync(file,"utf8"),m=h.match(/<script src="(data\/[^"]+\.js)"/);let list;
  if(m){const c={window:{}};vm.runInNewContext(fs.readFileSync(path.join(path.dirname(file),m[1]),"utf8"),c);
    list=((c.window.LP||c.LP||{}).panels||[]).map(p=>[p.id,typeof p.tab==="string"?p.tab:(p.tab||{}).en||(p.tab||{}).ca||p.id])}
  else list=[...h.matchAll(/<button class="tab[^"]*" data-panel="([^"]+)">([^<]+)</g)].map(x=>[x[1],x[2].replace(/^\d+\s+/,"").trim()]);
  if(list.length>1)out[a.id]=list;
}
const js="// Generated by tools/gen-sections.js: section tabs (panel id, English name) of each activity page, for the per-group section switches.\n"
  +"window.EL_SECTIONS={\n"+Object.entries(out).map(([k,v])=>"  "+JSON.stringify(k)+":"+JSON.stringify(v)).join(",\n")+"\n};\n";
fs.writeFileSync(path.join(R,"shared/js/el-sections.js"),js);
console.log(Object.keys(out).length+" activities");
